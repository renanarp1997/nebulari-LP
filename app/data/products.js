export const WHATSAPP_NUMBER = "5511900000000";

export function whatsAppUrl(product) {
  const base = `https://wa.me/${WHATSAPP_NUMBER}`;
  if (!product) {
    const msg = encodeURIComponent("Olá! Quero saber mais sobre as peças da Nebulari.");
    return `${base}?text=${msg}`;
  }
  const msg = encodeURIComponent(
    `Olá! Tenho interesse no ${product.name} (${product.collection}). Pode me contar mais?`
  );
  return `${base}?text=${msg}`;
}

export function getProduct(id) {
  return PRODUCTS.find((p) => p.id === id);
}

export function relatedProducts(id, limit = 3) {
  return PRODUCTS.filter((p) => p.id !== id).slice(0, limit);
}

export function formatBRL(value) {
  return value.toLocaleString("pt-BR", { style: "currency", currency: "BRL" });
}
